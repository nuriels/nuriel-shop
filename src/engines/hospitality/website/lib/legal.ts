/** הצהרת הנגישות — תבנית (טיוטה) */
export function accessibilitySections(site: PublicSite): LegalSection[] {
  const b = site.business;
  const placeAccess = [
    ...site.properties.flatMap((p) => p.amenities),
    ...site.units.flatMap((u) => u.amenities),
  ]
    .filter((a) => a.category === "accessibility")
    .map((a) => (a.note ? `${a.name} — ${a.note}` : a.name));
  return [
    {
      title: "מחויבות לנגישות",
      body: [
        `${b.name} רואה חשיבות במתן שירות שוויוני לכל האורחים, ובהם אנשים עם מוגבלות, ופועל להנגיש את האתר ואת המקום.`,
      ],
    },
    {
      title: "נגישות האתר",
      body: [
        "האתר נבנה בהתאם להנחיות הנגישות לתכני אינטרנט (WCAG 2.1, רמה AA) ולתקן הישראלי 5568, ככל שהדבר אפשרי.",
        'בין השאר: ניווט מלא במקלדת וקישור "דילוג לתוכן", מבנה כותרות ברור, טקסט חלופי לתמונות, ניגודיות צבעים, התאמה לנייד ולהגדלת טקסט, תמיכה בקוראי מסך ובכיוון מימין לשמאל.',
      ],
    },
    {
      title: "מגבלות ידועות",
      body: [
        "ייתכן שחלק מהתמונות שהעסק מעלה עדיין ללא תיאור מלא, ושסרטונים מוטמעים מאתרים חיצוניים אינם נגישים במלואם. אנו פועלים לתקן זאת.",
      ],
    },
    {
      title: "נגישות המקום",
      body: placeAccess.length
        ? placeAccess
        : ["לפרטים על הסדרי הנגישות במקום — פנו אלינו ונשמח לעזור לפני ההגעה."],
    },
    {
      title: "פניות בנושא נגישות",
      body: [
        `נתקלתם בבעיה או צריכים התאמה? פנו אלינו: ${contactLine(site) || "דרך פרטי הקשר באתר"}. נשתדל לענות בתוך זמן קצר.`,
      ],
    },
  ];
}
