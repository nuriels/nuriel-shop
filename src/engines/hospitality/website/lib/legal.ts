import type { PublicSite } from "../../types/website";

export const LEGAL_DRAFT_BANNER = "טיוטה – טרם אושרה לפרסום (ממתינה לבדיקה משפטית)";

export interface LegalSection {
  title: string;
  body: string[];
}

function contactLine(site: PublicSite): string {
  const b = site.business;
  return [
    b.phone && `טלפון ${b.phone}`,
    b.email && `אימייל ${b.email}`,
    b.address && `כתובת: ${b.address}`,
  ]
    .filter(Boolean)
    .join(" · ");
}

