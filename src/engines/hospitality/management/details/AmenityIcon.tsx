export function AmenityIcon({ name, className }: { name: string | null; className?: string }) {
  const Icon = (name && AMENITY_ICON_COMPONENTS[name as IconName]) || Check;
  return <Icon className={className ?? "size-4"} aria-hidden="true" />;
}
