import { ORDER_HOURS } from "@/lib/order-hours";

/**
 * טיוטת ברירת מחדל לתנאי שימוש ומדיניות פרטיות, מותאמת לדין הישראלי
 * (חוק הגנת הצרכן תשמ"א-1981, חוק הגנת הפרטיות תשמ"א-1981 ותיקון 13).
 *
 * חשוב: זוהי טיוטה כללית ואינה תחליף לייעוץ משפטי. יש להעביר לבדיקת
 * עורך/ת דין לפני פרסום, ובפרט את סעיפי הביטול, האחריות וגיל הרכישה.
 * הטקסט ניתן לעריכה מלאה בפאנל הניהול → הגדרות אתר.
 */

export type LegalBusinessInfo = {
  businessName: string;
  taxId: string;
  address: string;
  phone: string;
  email: string;
  sellsAlcohol: boolean;
};

function fallback(value: string, placeholder: string): string {
  return value.trim() !== "" ? value.trim() : placeholder;
}

export function defaultTermsOfService(info: LegalBusinessInfo): string {
  const name = fallback(info.businessName, "[שם העסק]");
  const taxId = fallback(info.taxId, '[מספר ח"פ / עוסק מורשה]');
  const address = fallback(info.address, "[כתובת העסק]");
  const phone = fallback(info.phone, "[טלפון]");
  const email = fallback(info.email, "[אימייל]");

  const alcoholClause = info.sellsAlcohol
    ? `
6. הגבלת גיל למכירת משקאות אלכוהוליים
המערכת כוללת מוצרים המהווים "משקה משכר" כהגדרתו בחוק. מכירת אלכוהול קטינים מתחת לגיל 18 אסורה על פי חוק (חוק הגנת הציבור מפני עבריינות מין ותיקוני חקיקה בנוגע למכירת אלכוהול לקטינים, וחוק רישוי עסקים). הרשמה למערכת ו/או ביצוע הזמנה הכוללת משקאות אלכוהוליים מהווה הצהרה כי המשתמש בגיר בן 18 שנים ומעלה. ${name} רשאית לדרוש הצגת תעודה מזהה בעת אספקת ההזמנה, ולבטל הזמנה במידה שהתעורר חשד סביר כי הרוכש קטין.
`
    : "";

  return `תנאי שימוש — ${name}

עדכון אחרון: [להשלמה בעת הפרסום]

1. כללי
תנאי שימוש אלה חלים על השימוש באתר ובמערכת ההזמנות של ${name} ("המערכת", "האתר"), לרבות עיון בקטלוג, הרשמה כלקוח עסקי, וביצוע הזמנות. הגלישה והשימוש במערכת מהווים הסכמה לתנאים אלה במלואם. אם אינך מסכימ/ה לתנאים — נא להימנע משימוש במערכת.

2. אופי השירות — מסחר סיטונאי בין עסקים (B2B)
המערכת מיועדת לביצוע הזמנות סיטונאיות בין עסקים בלבד. ההרשמה וההזמנה מותרות לעוסקים מורשים/חברות בעלי ח.פ תקף. תצוגת הקטלוג לגולש אנונימי אינה מהווה הצעה מחייבת ואינה כוללת מחירים; המחירים מוצגים אך ורק למשתמשים רשומים ומאושרים, בהתאם לקבוצת המחיר שהוקצתה להם.

3. הרשמה, אישור חשבון ושיוך לסוכן
פתיחת חשבון לקוח כפופה לאישור מנהל המערכת ומחייבת מסירת פרטי עסק מלאים ומדויקים (שם עסק, כתובת, מספר ח.פ/עוסק מורשה, איש קשר, טלפון ואימייל). כל לקוח משויך לסוכן/ת מכירות מטעם ${name}, שישמש איש הקשר המרכזי לצורך אישור ההזמנה, שינויים ותיאום אספקה. ${name} רשאית לסרב לאשר חשבון, לחסום חשבון או לשנות את שיוך הסוכן לפי שיקול דעתה.

4. הזמנות, מחירים ואישור סופי
הצגת מוצר במערכת וביצוע הזמנה על ידי הלקוח מהווים הצעה בלבד; ההזמנה תיכנס לתוקף רק לאחר אישורה בפועל על ידי הסוכן/ת המטפל/ת או מנהל המערכת, לרבות אישור זמינות מלאי, מחיר וכמות. ${name} רשאית לעדכן מחירים, לתקן טעות סופר/מחיר, לשנות כמויות או לבטל פריטים בהזמנה טרם אישורה הסופי, ותודיע על כך ללקוח. כל המחירים במערכת נקובים בשקלים חדשים (₪) ואינם כוללים מע"מ אלא אם צוין אחרת.
   4.1. ${ORDER_HOURS.terms}

5. תמונות המוצרים
כל תמונות המוצרים המוצגות באתר הן להמחשה בלבד, וייתכנו הבדלים בין התמונה למוצר בפועל (עיצוב אריזה, נפח, גוון וכיו"ב). אין להסתמך על התמונה כמפרט מחייב של המוצר.
${alcoholClause}
7. מדיניות ביטול עסקה
העסקאות המבוצעות במערכת הן עסקאות מכר סיטונאיות בין עסקים לצורך עיסוקו של הלקוח, ולא עסקאות "צרכן" כהגדרתן בחוק הגנת הצרכן, תשמ"א-1981 (החוק ותקנותיו, לרבות הוראות הביטול בעסקת מכר מרחוק, חלות על רכישה שאינה למטרה עסקית). על אף האמור, ${name} תפעל בהגינות ובתום לב בכל הנוגע לביטולים:
   7.1. ניתן לבטל או לתקן הזמנה ללא עלות כל עוד לא אושרה סופית ע"י הסוכן/ת ולא יצאה להכנה/שילוח — בפנייה לסוכן המטפל.
   7.2. ביטול לאחר אישור ההזמנה ו/או לאחר שיצאה לביצוע ייבחן לפי נסיבות העניין, ועשוי לחייב בדמי ביטול או בעלות המשלוח שכבר יצא לפועל.
   7.3. מוצרי מזון/משקאות שאריזתם נפתחה, ניזוקו, או שפג תוקפם אינם ניתנים להחזרה מטעמי בריאות הציבור ותברואה.
   7.4. מוצר שסופק פגום או שלא בהתאם להזמנה יוחלף/יזוכה במלואו בהתאם לדין.

8. אחריות והגבלת אחריות
המידע באתר (לרבות זמינות מלאי, תיאורים ותמונות) מוצג כמות שהוא ("AS IS") ועשוי להשתנות ללא הודעה מוקדמת. ${name} אינה אחראית לנזק עקיף, תוצאתי או אגבי הנובע משימוש במערכת, ככל שהדבר מותר על פי דין. אין באמור כדי לגרוע מאחריות המוטלת על פי חוק אחריות למוצרים פגומים, תשמ"א-1980, ומכל דין קוגנטי אחר שאינו ניתן להתניה.

9. קניין רוחני
כל הזכויות בתכני האתר, לרבות טקסטים, תמונות, סימני מסחר ועיצוב, שייכות ל-${name} או לצדדים שלישיים שהעניקו לה רישיון שימוש, ואין להעתיקן או להשתמש בהן ללא אישור מראש ובכתב.

10. פרטיות
השימוש במידע האישי הנמסר במערכת כפוף למדיניות הפרטיות של ${name}, המהווה חלק בלתי נפרד מתנאים אלה.

11. נגישות
${name} פועלת להנגשת האתר בהתאם לתקן הישראלי ת"י 5568 ולתקנות שוויון זכויות לאנשים עם מוגבלות (התאמות נגישות לשירות), תשע"ג-2013. פניות בנושא נגישות ניתן להפנות לפרטי הקשר המופיעים מטה.

12. דין וסמכות שיפוט
על תנאים אלה יחולו דיני מדינת ישראל בלבד, וסמכות השיפוט הבלעדית בכל עניין הנוגע להם נתונה לבתי המשפט המוסמכים במחוז שבו מתנהל עסקה של ${name}.

13. פרטי התקשרות
${name}, ח.פ/עוסק מורשה ${taxId}
כתובת: ${address}
טלפון: ${phone}
אימייל: ${email}
`;
}

export function defaultPrivacyPolicy(info: LegalBusinessInfo): string {
  const name = fallback(info.businessName, "[שם העסק]");
  const address = fallback(info.address, "[כתובת העסק]");
  const phone = fallback(info.phone, "[טלפון]");
  const email = fallback(info.email, "[אימייל]");

  return `מדיניות פרטיות — ${name}

עדכון אחרון: [להשלמה בעת הפרסום]

1. כללי
מדיניות פרטיות זו מפרטת כיצד ${name} אוספת, משתמשת ומאבטחת מידע אישי הנמסר במסגרת השימוש במערכת ההזמנות, בהתאם לחוק הגנת הפרטיות, תשמ"א-1981 ותיקון מס' 13 לחוק.

2. איזה מידע נאסף
בעת הרשמה ושימוש במערכת ייאסף מידע הכולל: שם עסק, מספר ח.פ/עוסק מורשה, כתובת, שם איש קשר, טלפון ואימייל, היסטוריית הזמנות ופרטי התקשרות עם הסוכן/ת המטפל/ת. בנוסף נאספים נתוני שימוש טכניים בסיסיים (כגון עוגיות הגדרות תצוגה/נגישות הנשמרות בדפדפן).

3. מטרות השימוש במידע
המידע משמש לצורך: ניהול חשבון הלקוח ואישורו; עיבוד, אישור ואספקת הזמנות; יצירת קשר בעניין הזמנות; שליחת אישורי הזמנה ועדכוני סטטוס בדוא"ל; מניעת הונאות ותפעול תקין של המערכת; ועמידה בדרישות דין (לרבות חשבוניות ורישומים חשבונאיים).

4. מסירת מידע לצדדים שלישיים
המידע אינו נמכר לצדדים שלישיים. המידע עשוי להיות מועבר לספקי שירות הפועלים מטעם ${name} לצורך תפעול המערכת בלבד (כגון שירותי אחסון ענן ושליחת דוא"ל), ואלה מחויבים בשמירה על סודיות ואבטחת המידע. מידע עשוי להימסר גם אם נדרש על פי דין, צו שיפוטי, או כדי להגן על זכויות ${name}.

5. אבטחת מידע
${name} נוקטת אמצעי אבטחה סבירים המקובלים בתעשייה (לרבות הצפנת תעבורה, בקרת הרשאות לפי תפקיד ומדיניות גישה מבוססת תפקידים) כדי להגן על המידע מפני גישה, שימוש או חשיפה בלתי מורשים. עם זאת, לא ניתן להבטיח הגנה מוחלטת מפני כל פגיעה.

6. זכויות המשתמש
בהתאם לחוק הגנת הפרטיות, כל משתמש רשאי לבקש לעיין במידע שנשמר אודותיו, לבקש את תיקונו אם אינו נכון, ובכפוף לדין — לבקש את מחיקתו. פניות בנושא זה ניתן להפנות לפרטי הקשר שלהלן.

7. שמירת מידע
המידע יישמר למשך הזמן הנדרש למטרות שלשמן נאסף ובהתאם לחובות שמירת רישומים על פי דין (לרבות דיני מיסים וחשבונאות).

8. עוגיות (Cookies) ואחסון מקומי
המערכת עושה שימוש באחסון מקומי בדפדפן לשמירת העדפות תצוגה ונגישות בלבד, ואינה כוללת מעקב פרסומי צד-שלישי.

9. פניות בנושא פרטיות
לכל שאלה, בקשה או תלונה בנושא פרטיות ניתן לפנות אל:
${name}
כתובת: ${address}
טלפון: ${phone}
אימייל: ${email}
`;
}
