// שלב א' 7 — חבילות, מקצה לקצה:
//   • בעל העסק יוצר "חבילת כלה" במסך "חבילות" — נשמרת מוסתרת; מציג — והיא בעמוד הבית;
//   • באתר: כרטיס החבילה → עמוד החבילה (מחיר, תנאים) → הזמנה: רק תאריך הגעה, 2 לילות, מחיר החבילה
//     והתנאים בסיכום → בקשה → "הבקשה התקבלה" עם שם החבילה, ומייל לאורח עם שם החבילה;
