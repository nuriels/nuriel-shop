//   • אותם לילות שוב — "לא פנויים" (אותה תפוסה של היחידה), ואי אפשר להמשיך.

test.describe.configure({ mode: "serial" });

const OWNER = { email: "pk.owner@e2e.test", password: "Pk-Owner-Pass-1!" };
const SLUG = "pk-site";
const HOST = hostOf(SLUG);
const URL_ = (path = "/") => `http://${HOST}:${PORT}${path}`;
const GUEST = "pk.bride@e2e.test";
const NAME = "חבילת כלה – שני לילות ב-VIP";
let siteId = "";
let owner: SavedSession | null = null;
const FLAGS = [
  "hospitality_backend_enabled",
  "hospitality_management_enabled",
  "hospitality_frontend_enabled",
  "hospitality_booking_enabled",
] as const;

function cleanup() {
  const id = sql(`SELECT id FROM public.tenants WHERE slug = '${SLUG}'`);
  if (id) asPlatform(`SELECT public.platform_delete_tenant('${id}', '${SLUG}')`);
}

/** מיילים לכתובת מאז זמן מסוים שמכילים טקסט */
async function mailsWith(request: APIRequestContext, to: string, text: string, since: number) {
  const calls = (await (await request.get("http://127.0.0.1:4010/__calls")).json()) as {
    url: string;
    body: string;
    at: number;
  }[];
  return calls.filter(
    (c) =>
      c.url.startsWith("/emails") && c.at >= since && c.body.includes(to) && c.body.includes(text),
  ).length;
}

test.beforeAll(async ({ request }, testInfo) => {
  test.skip(testInfo.project.name === "mobile", "the packages flow runs once, on the computer");
  cleanup();
  const ownerId = await ensureUser(request, OWNER);
  asPlatform(`SELECT hospitality.admin_open_site('${SLUG}', 'נופי החבילות', '${OWNER.email}')`);
  siteId = sql(`SELECT id FROM public.tenants WHERE slug = '${SLUG}'`);
  sql(`INSERT INTO public.user_roles (tenant_id, user_id, email, username, role, is_approved)
       VALUES ('${siteId}', '${ownerId}', '${OWNER.email}', 'pk_owner', 'admin', true) ON CONFLICT DO NOTHING`);
  sql(
    `UPDATE public.platform_feature_flags SET enabled = true WHERE key IN (${FLAGS.map((f) => `'${f}'`).join(", ")})`,
  );
  sql(`INSERT INTO public.tenant_feature_flags (tenant_id, key, enabled) VALUES
       ${FLAGS.map((f) => `('${siteId}', '${f}', true)`).join(", ")}
       ON CONFLICT (tenant_id, key) DO UPDATE SET enabled = true`);
  const propertyId = sql(`INSERT INTO hospitality.properties (tenant_id, name, slug, status)
       VALUES ('${siteId}', 'נופי החבילות', 'pk-p', 'active') RETURNING id`);
  // היחידות פתוחות להזמנה שנה קדימה; ה-VIP דורשת בדרך כלל 3 לילות — החבילה קובעת 2
  sql(`INSERT INTO hospitality.units (tenant_id, property_id, kind, name, slug, capacity, base_occupancy, base_price,
                                      min_nights, open_until)
       VALUES ('${siteId}', '${propertyId}', 'unit', 'סוויטת VIP', 'pk-vip', 4, 2, 900, 3, current_date + 365),
              ('${siteId}', '${propertyId}', 'unit', 'צימר הגפן', 'pk-u2', 2, 2, 600, 1, current_date + 365)`);
  await expect
    .poll(async () => (await hostGet(request, HOST, "/stay")).status(), { timeout: 20_000 })
    .toBe(200);
  owner = await passwordSession(request, URL_(""), OWNER);
});

test.afterAll(() => {
  cleanup();
  sql(`UPDATE public.platform_feature_flags SET enabled = false WHERE key LIKE 'hospitality%'`);
});

test("the owner creates a bride package — saved hidden; shown — it is on the home page", async ({
  page,
  browser,
}) => {
  await loadSession(page, owner!, "/manage/packages");
  await expect(page.getByRole("heading", { level: 1, name: "חבילות" })).toBeVisible();
  await page.getByRole("button", { name: "חבילה חדשה" }).click();
  await page.getByLabel("שם החבילה").fill(NAME);
  await page.getByLabel("היחידה").selectOption({ label: "סוויטת VIP" });
  await page.getByLabel("לילות").fill("2");
  await page.getByLabel("מחיר החבילה (₪)").fill("2400");
  await page.getByLabel("עד כמה אורחים").fill("2");
  await page.getByLabel("תיאור").fill("שני לילות בסוויטה עם עיצוב חדר, בקבוק יין וארוחת בוקר.");
  await page.getByLabel("תנאי החבילה").fill("לא כולל ארוחות ערב.");
  await page.getByRole("button", { name: "יצירת החבילה" }).click();
  const row = page.locator(`[data-package-row="${NAME}"]`);
  await expect(row).toBeVisible({ timeout: 15_000 });
  await expect(row).toContainText("מוסתרת");
  await expect(row).toContainText("סוויטת VIP");
  await expectAccessible(page, "packages screen");

  // מוסתרת — לא באתר
  const visitor = await browser.newPage();
  await visitor.goto(URL_("/stay"));
  await expect(visitor.getByRole("banner")).toBeVisible();
  await expect(visitor.getByTestId("site-packages")).toHaveCount(0);

  await row.getByRole("switch", { name: "מוצגת באתר" }).click();
  await expect(row.getByRole("switch", { name: "מוצגת באתר" })).toHaveAttribute(
    "aria-checked",
    "true",
  );
  await expect(row).not.toContainText("מוסתרת");
  await visitor.goto(URL_("/stay"));
  const section = visitor.getByTestId("site-packages");
  await expect(section).toBeVisible();
  await expect(section).toContainText(NAME);
  await expect(section).toContainText("2,400");
  await expect(section).toContainText("חבילה מיוחדת");
  await visitor.close();
});

test("a guest books the package — arrival only, 2 nights at the package price, its terms; the request shows the package", async ({
  page,
  request,
}) => {
  await page.goto(URL_("/stay"));
  await page
    .getByTestId("site-packages")
    .getByRole("link", { name: new RegExp(NAME) })
    .click();
  await expect(page).toHaveURL(/\/stay\/packages\//);
  await expect(page.getByRole("heading", { level: 1, name: NAME })).toBeVisible();
  await expect(page.getByTestId("package-price")).toContainText("2,400");
  await expect(page.getByTestId("package-terms")).toContainText("לא כולל ארוחות ערב");
  await expectAccessible(page, "package page");

  await page.getByRole("link", { name: "להזמנת החבילה" }).click();
  await expect(page).toHaveURL(/\/stay\/book\?package=/);
  await expect(page.getByTestId("package-booking")).toBeVisible();
  await page.getByRole("button", { name: "החודש הבא" }).first().click();
  await page.getByRole("button", { name: "10 — פנוי" }).first().click();
  // יום אחד — והעזיבה אחרי 2 הלילות של החבילה; המחיר — של החבילה (לא 2 × 900)
  const summary = page.locator("aside").filter({ hasText: "סיכום" });
  await expect(summary).toContainText("2 לילות");
  await expect(summary).toContainText("מחיר החבילה");
  await expect(summary).toContainText("2,400");
  await expect(summary).not.toContainText("1,800");
  await expect(summary.getByTestId("package-terms-summary")).toContainText("לא כולל ארוחות ערב");
  await page.getByRole("button", { name: "המשך לפרטים" }).click();
  await page.getByLabel("שם מלא").fill("נועה כלה");
  await page.getByLabel("טלפון נייד").fill("0521234570");
  await page.getByLabel("אימייל").first().fill(GUEST);
  await page.getByRole("checkbox", { name: /קראתי ואני מאשר/ }).check();
  const since = Date.now();
  await page.getByRole("button", { name: "שליחת בקשת הזמנה" }).click();
  await expect(page).toHaveURL(/\/stay\/booking-received/, { timeout: 20_000 });
  await expect(page.getByRole("heading", { level: 1, name: "הבקשה התקבלה" })).toBeVisible();
  await expect(page.getByText(NAME)).toBeVisible({ timeout: 15_000 });
  await expectAccessible(page, "package request received");

  // במסד: על ה-VIP, 2 לילות, במחיר החבילה ועם החבילה
  expect(
    sql(`SELECT u.name || '|' || (b.check_out - b.check_in) || '|' || b.total::int || '|' || (b.package_snapshot ->> 'name')
           FROM hospitality.bookings b
           JOIN hospitality.guests g ON g.id = b.guest_id
           JOIN hospitality.units u ON u.id = b.unit_id
          WHERE b.tenant_id = '${siteId}' AND g.email_normalized = '${GUEST}'`),
  ).toBe(`סוויטת VIP|2|2400|${NAME}`);
  // המייל לאורח — עם שם החבילה
  await expect
    .poll(() => mailsWith(request, GUEST, NAME, since), { timeout: 20_000 })
    .toBeGreaterThan(0);
});

test("the same nights again — not available (the unit is taken), no continuing; the owner's booking page shows the package", async ({
  page,
}) => {
  const [checkIn, slug, bookingId] = sql(
    `SELECT b.check_in || '|' || p.slug || '|' || b.id FROM hospitality.bookings b
       JOIN hospitality.packages p ON p.id = b.package_id WHERE b.tenant_id = '${siteId}'`,
  ).split("|");
  await page.goto(URL_(`/stay/book?package=${encodeURIComponent(slug!)}&from=${checkIn}`));
  await expect(page.getByTestId("package-booking")).toBeVisible();
  const summary = page.locator("aside").filter({ hasText: "סיכום" });
  await expect(summary).toContainText("כבר לא פנויים", { timeout: 15_000 });
  await expect(page.getByRole("button", { name: "המשך לפרטים" })).toBeDisabled();

  await loadSession(page, owner!, `/manage/bookings/${bookingId}`);
  const card = page.getByTestId("booking-package");
  await expect(card).toBeVisible({ timeout: 15_000 });
  await expect(card).toContainText("2 לילות");
  await expect(card).toContainText("2,400");
  await expect(card).toContainText("לא כולל ארוחות ערב");
  await expect(page.getByRole("heading", { name: `חבילה — ${NAME}` })).toBeVisible();
});
