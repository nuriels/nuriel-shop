-- עמוד התקנון מציג את site_settings.terms_content אם נשמר בניהול, ורק אם הוא
-- ריק — את ברירת המחדל מהקוד (שכבר כוללת את הסעיף, src/lib/legal.ts).
-- כאן: אם נשמר נוסח ואין בו עדיין את הסעיף — מוסיפים אותו כ-4.1 מתחת לסעיף
-- "4. הזמנות, מחירים ואישור סופי"; אם הסעיף הזה לא קיים בנוסח — בסוף הנוסח.
-- נוסח ריק / שכבר כולל את הסעיף — לא נוגעים. אידמפוטנטי.
-- ============================================================
DO $$
DECLARE
  t TEXT;
  clause CONSTANT TEXT := 'שעות קבלת הזמנות וטיפול: שעת הסגירה לקליטת הזמנות לטיפול באותו יום עסקים הינה 16:00. הזמנה שתישלח לאחר השעה 16:00 תיחשב כהזמנה שהתקבלה ביום העסקים העוקב ותועבר לטיפול הסוכן ולהסדרת תשלום בהתאם.';
BEGIN
  SELECT terms_content INTO t FROM public.site_settings WHERE id = true;
  IF t IS NULL OR btrim(t) = '' OR position('שעות קבלת הזמנות וטיפול' IN t) > 0 THEN
    RETURN;
  END IF;
  IF t ~ '4\. הזמנות, מחירים ואישור סופי\n[^\n]+' THEN
    t := regexp_replace(t, '(4\. הזמנות, מחירים ואישור סופי\n[^\n]+)', E'\\1\n   4.1. ' || clause);
  ELSE
    t := rtrim(t) || E'\n\n' || clause;
  END IF;
  UPDATE public.site_settings SET terms_content = t WHERE id = true;
END $$;
